    private static string GetComparisonScript(string leftJson, string rightJson, string leftRoot, string rightRoot) => $$"""
        <script>
        const leftData  = {{leftJson}};
        const rightData = {{rightJson}};
        const leftRoot  = {{JsonSerializer.Serialize(leftRoot)}};
        const rightRoot = {{JsonSerializer.Serialize(rightRoot)}};

        function getRelPath(fullPath, root) {
          if (fullPath === root) return '';
          return fullPath.slice(root.length).replace(/^[\/\\]+/, '').toLowerCase();
        }

        const leftByRel  = new Map();
        const rightByRel = new Map();
        leftData.forEach(f  => { f.rel = getRelPath(f.p, leftRoot);  leftByRel.set(f.rel,  f); });
        rightData.forEach(f => { f.rel = getRelPath(f.p, rightRoot); rightByRel.set(f.rel, f); });

        function permsKey(pm) { return (pm||[]).map(p => p.i+'|'+p.a+'|'+p.r).sort().join(';'); }

        leftData.forEach(f => {
          const r = rightByRel.get(f.rel);
          if (!r) f.diffStatus = 'left-only';
          else if (permsKey(f.pm) === permsKey(r.pm)) f.diffStatus = 'same';
          else f.diffStatus = 'changed';
        });
        rightData.forEach(f => {
          const l = leftByRel.get(f.rel);
          if (!l) f.diffStatus = 'right-only';
          else if (permsKey(f.pm) === permsKey(l.pm)) f.diffStatus = 'same';
          else f.diffStatus = 'changed';
        });

        function buildTree(data) {
          data.forEach(f => { f.children = []; });
          const map = new Map(data.map(f => [f.p, f]));
          data.forEach(f => { if (f.pr && map.has(f.pr)) map.get(f.pr).children.push(f); });
          return data.find(f => !f.pr || f.pr === f.p) || data[0];
        }

        const leftRoot2  = buildTree(leftData);
        const rightRoot2 = buildTree(rightData);

        function escHtml(s) {
          if (!s) return '';
          return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');
        }

        function createCompareNode(folder, parentEl) {
          const nodeDiv = document.createElement('div');
          nodeDiv.className = 'folder-node';
          nodeDiv.dataset.path = folder.p;
          nodeDiv.dataset.rel  = folder.rel;
