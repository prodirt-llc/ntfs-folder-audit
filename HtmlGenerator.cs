    // -----------------------------------------------------------------------
    // Private helpers
    // -----------------------------------------------------------------------
    private static string SerializeFolders(List<FolderNode> folders)
    {
        var sb = new StringBuilder("[");
        for (int i = 0; i < folders.Count; i++)
        {
            var f = folders[i];
            if (i > 0) sb.Append(',');
            sb.Append("{\"p\":").Append(JsonStr(f.Path));
            sb.Append(",\"n\":").Append(JsonStr(f.Name));
            sb.Append(",\"pr\":").Append(JsonStr(f.ParentPath));
            sb.Append(",\"d\":").Append(f.Depth);
            if (f.InheritanceBroken) sb.Append(",\"bi\":true");
            if (f.AccessDenied)      sb.Append(",\"ad\":true");

            // Only serialize EXPLICIT (non-inherited) permissions.
            // Inherited perms are resolved at display time by walking up folderMap in the JS.
            var explicit_ = f.Permissions.Where(p => !p.IsInherited).ToList();
            var inherited_ = f.Permissions.Where(p => p.IsInherited).ToList();
            sb.Append(",\"pm\":[");
            for (int j = 0; j < explicit_.Count; j++)
            {
                var p = explicit_[j];
                if (j > 0) sb.Append(',');
                sb.Append("{\"i\":").Append(JsonStr(p.Identity));
                var rights = (!string.IsNullOrEmpty(p.RightsDecoded) && p.RightsDecoded != p.Rights)
                    ? p.RightsDecoded : p.Rights;
                sb.Append(",\"r\":").Append(JsonStr(rights));
                if (p.AccessType != "Allow") sb.Append(",\"a\":").Append(JsonStr(p.AccessType));
                sb.Append('}');
            }
            // Store inherited count so JS knows how many exist
            int inheritedCount = inherited_.Count;
            sb.Append("]");
            if (inheritedCount > 0) sb.Append(",\"ic\":").Append(inheritedCount);
            sb.Append('}');
        }
        sb.Append(']');
        return sb.ToString();
    }

    private static string JsonStr(string s) => JsonSerializer.Serialize(s, JsonOpts);

    private static string EscapeHtml(string s) =>
        s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\"", "&quot;");

