    private static string GetSingleScript(string json, string rootPath) => $$"""
        <script>
        const flatData = {{json}};
        const rootPath = {{JsonSerializer.Serialize(rootPath)}};
        console.log('Loaded ' + flatData.length + ' folders');
        const folderMap = new Map();
        flatData.forEach(f => { f.children = []; folderMap.set(f.p, f); });
        flatData.forEach(f => { if (f.pr && folderMap.has(f.pr)) folderMap.get(f.pr).children.push(f); });
        const rootFolder = flatData.find(f => !f.pr || f.pr === f.p) || flatData[0];

        function hasDenyRule(pm) { return pm && pm.some(p => p.a === 'Deny'); }

        function createNode(folder, parentEl) {
          const nodeDiv = document.createElement('div');
          nodeDiv.className = 'folder-node';
          nodeDiv.dataset.path = folder.p;
          nodeDiv.dataset.depth = folder.d;
          if (folder.bi) nodeDiv.dataset.bi = '1';
          if (folder.ad) nodeDiv.dataset.ad = '1';

          const hasKids = folder.children && folder.children.length > 0;
          const hasDeny = hasDenyRule(folder.pm);

          const header = document.createElement('div');
          let headerClass = 'folder-header';
          if (folder.bi) headerClass += ' broken-inheritance';
          else if (folder.ad) headerClass += ' access-denied';
          header.className = headerClass;

          const icon = document.createElement('span');
          icon.className = hasKids ? 'expand-icon has-children collapsed' : 'expand-icon no-children';

          const folderIcon = document.createElement('span');
          folderIcon.className = 'folder-icon';
          folderIcon.textContent = folder.ad ? '\uD83D\uDD12' : (folder.bi ? '\u26A0\uFE0F' : '\uD83D\uDCC1');

          const name = document.createElement('span');
          name.className = 'folder-name';
          name.textContent = folder.n || folder.p;
          name.title = folder.p;

          const count = document.createElement('span');
          count.className = 'perm-count' + (hasDeny ? ' has-deny' : '');
          // Show explicit count + inherited count from ancestors
          const ownExplicit = folder.pm ? folder.pm.length : 0;
          let ancInherited = 0;
          let ancCur = folder;
          while (ancCur && ancCur.pr) {
            const anc = folderMap.get(ancCur.pr);
            if (!anc) break;
            ancInherited += anc.pm ? anc.pm.length : 0;
            ancCur = anc;
          }
          count.textContent = ownExplicit + ancInherited;
          if (ownExplicit === 0 && ancInherited > 0) count.title = ancInherited + ' inherited';
          else if (ancInherited > 0) count.title = ownExplicit + ' explicit + ' + ancInherited + ' inherited';

          const btn = document.createElement('button');
          btn.className = 'perm-button';
          btn.textContent = 'Perms';
          btn.onclick = e => { e.stopPropagation(); togglePerms(nodeDiv); };

          header.appendChild(icon);
          header.appendChild(folderIcon);
          header.appendChild(name);
          header.appendChild(count);
          header.appendChild(btn);

          if (folder.bi) {
            const badge = document.createElement('span');
            badge.className = 'bi-badge';
            badge.textContent = '\u26A0';
            badge.title = 'Inheritance disabled — permissions are set explicitly on this folder, not inherited from parent.';
            header.appendChild(badge);
          }
          if (folder.ad) {
            const badge = document.createElement('span');
            badge.className = 'ad-badge';
            badge.textContent = '\uD83D\uDD12 Access Denied';
            header.appendChild(badge);
          }

          if (hasKids) header.onclick = () => toggleKids(nodeDiv, icon);

          const panel = document.createElement('div');
          panel.className = 'permissions-panel';
          {
            const explicitPerms = folder.pm || [];
            // Walk up folderMap collecting all ancestor explicit perms
            const inheritedRows = [];
            let cur = folder;
            while (cur && cur.pr) {
              const anc = folderMap.get(cur.pr);
              if (!anc) break;
              if (anc.pm && anc.pm.length > 0) {
                anc.pm.forEach(p => inheritedRows.push({ p, src: anc.p }));
              }
              cur = anc;
            }
            let html = '<table><thead><tr><th>Identity</th><th>Rights</th><th>Access</th><th>Source</th></tr></thead><tbody>';
            if (explicitPerms.length > 0) {
              html += '<tr><td colspan="4" style="background:#f0f4ff;font-size:11px;font-weight:700;color:#667eea;padding:4px 10px;letter-spacing:.5px">EXPLICIT PERMISSIONS</td></tr>';
              explicitPerms.forEach(p => {
                const ac = (p.a && p.a !== 'Allow') ? 'deny' : 'allow';
                html += '<tr><td>' + escHtml(p.i) + '</td><td><span class="rights-decoded">' + escHtml(p.r) + '</span></td><td class="' + ac + '">' + (p.a||'Allow') + '</td><td><span class="inherited-no">Explicit</span></td></tr>';
              });
            }
            if (inheritedRows.length > 0) {
              html += '<tr><td colspan="4" style="background:#f8f9fc;font-size:11px;font-weight:700;color:#6c757d;padding:4px 10px;letter-spacing:.5px">INHERITED PERMISSIONS</td></tr>';
              inheritedRows.forEach(({ p, src }) => {
                const ac = (p.a && p.a !== 'Allow') ? 'deny' : 'allow';
                const shortSrc = src.split('\\').pop() || src;
                html += '<tr style="opacity:0.85"><td>' + escHtml(p.i) + '</td><td><span class="rights-decoded">' + escHtml(p.r) + '</span></td><td class="' + ac + '">' + (p.a||'Allow') + '</td><td><span class="inherited-yes" title="' + escHtml(src) + '">&#8593; ' + escHtml(shortSrc) + '</span></td></tr>';
              });
            }
            if (explicitPerms.length === 0 && inheritedRows.length === 0) {
              html += '<tr><td colspan="4" style="padding:10px;color:#6c757d">No permissions found' + (folder.ad ? ' (Access Denied)' : '') + '</td></tr>';
            }
            html += '</tbody></table>';
            panel.innerHTML = html;
          }

          nodeDiv.appendChild(header);
          nodeDiv.appendChild(panel);

          if (hasKids) {
            const cont = document.createElement('div');
            cont.className = 'children-container';
            folder.children.forEach(kid => createNode(kid, cont));
            nodeDiv.appendChild(cont);
          }
          parentEl.appendChild(nodeDiv);
        }

        function escHtml(s) {
          if (!s) return '';
          return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');
        }
        // Walk up the folder map to find the nearest ancestor with explicit permissions
        function findPermSource(folder) {
          let cur = folder;
          while (cur && cur.pr) {
            const parent = folderMap.get(cur.pr);
            if (!parent) break;
            if (parent.pm && parent.pm.length > 0) return parent;
            cur = parent;
          }
          return null;
        }
        function toggleKids(node, icon) {
          const cont = node.querySelector(':scope > .children-container');
          if (!cont) return;
          const exp = cont.classList.toggle('expanded');
          icon.classList.toggle('collapsed', !exp);
          icon.classList.toggle('expanded', exp);
        }
        function togglePerms(node) { node.querySelector('.permissions-panel').classList.toggle('visible'); }
        function expandAll() {
          document.querySelectorAll('.children-container').forEach(e => e.classList.add('expanded'));
          document.querySelectorAll('.expand-icon.has-children').forEach(e => { e.classList.remove('collapsed'); e.classList.add('expanded'); });
