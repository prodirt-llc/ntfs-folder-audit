          const name = document.createElement('span');
          name.className = 'folder-name';
          name.textContent = folder.n || folder.p;
          name.title = folder.p;

          const cnt = document.createElement('span');
          cnt.className = 'perm-count';
          cnt.textContent = (folder.pm||[]).length;

